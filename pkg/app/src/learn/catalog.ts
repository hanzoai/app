function buildStandardLabSteps(seed: CourseSeed): CourseLabStep[] {
  return [
    {
      id: `${seed.slug}-lab-1`,
      stepNumber: 1,
      title: 'Verify Environment & IAM Session',
      objective: `Confirm Hanzo CLI identity, active organization scope, and live connectivity to ${seed.endpoint}.`,
      endpoint: seed.endpoint,
      snippetLanguage: 'bash',
      snippet: `hanzo doctor && hanzo auth show\n${seed.cliCommand} --dry-run`,
      verificationHint: 'Confirm your active IAM user, org slug, and HTTP 200 readiness check.',
    },
    {
      id: `${seed.slug}-lab-2`,
      stepNumber: 2,
      title: 'Establish Baseline & Pre-Registered Metric',
      objective: `Capture a reproducible baseline run for ${seed.title} with explicit acceptance criteria before modifying configs or models.`,
      endpoint: seed.endpoint,
      snippetLanguage: 'bash',
      snippet: `${seed.cliCommand} --baseline ./evals/${seed.slug}-baseline.json`,
      verificationHint: 'Record baseline score, latency p95, and SHA-256 input manifest.',
    },
    {
      id: `${seed.slug}-lab-3`,
      stepNumber: 3,
      title: 'Implement & Execute Candidate Pipeline',
      objective: `Run your candidate implementation against live Hanzo Cloud (${seed.endpoint}) with IAM bearer authentication.`,
      endpoint: seed.endpoint,
      snippetLanguage: 'typescript',
      snippet: `const res = await fetch('https://api.hanzo.ai${seed.endpoint.replace(/^[A-Z]+\s+/, '')}', {\n  method: 'POST',\n  headers: {\n    Authorization: \`Bearer \${iamToken}\`,\n    'Content-Type': 'application/json',\n  },\n  body: JSON.stringify({ course: '${seed.slug}', mode: 'verify' }),\n})\nconsole.log(res.status, await res.json())`,
      verificationHint: 'Inspect structured JSON output and verify zero schema violations.',
    },
    {
      id: `${seed.slug}-lab-4`,
      stepNumber: 4,
      title: 'Run Regression Audit & Package Capstone Evidence',
      objective: 'Compare candidate vs baseline metrics, verify zero regressions, and export receipts for Capstone verification.',
      endpoint: 'POST /v1/research/compare',
      snippetLanguage: 'bash',
      snippet: `hanzo science compare --baseline ./evals/${seed.slug}-baseline.json --candidate ./evals/${seed.slug}-cand.json`,
      verificationHint: 'Confirm pre-registered threshold passed before submitting on the Capstone tab.',
    },
  ]
}

