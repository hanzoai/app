export const COURSE_BY_SLUG: Readonly<Record<string, CourseSpec>> = Object.fromEntries(
  COURSES.map((c) => [c.slug, c]),
)

export function getCourse(slug: string | null | undefined): CourseSpec | null {
  if (!slug) return null
  return COURSE_BY_SLUG[slug.trim().toLowerCase()] ?? null
}

export interface AdventureRecommendation {
  goal: AdventureGoal
  starter: CourseSpec
  coreCourses: CourseSpec[]
  certification: CertificationTrack
  firstLabCourse: CourseSpec
  firstLabHref: string
  docsLinks: readonly { title: string; url: string }[]
}

export function recommendAdventureTrack(goalId: AdventureGoalId): AdventureRecommendation {
  const goal = ADVENTURE_GOALS.find((g) => g.id === goalId) ?? ADVENTURE_GOALS[0]!
  const starter = COURSE_BY_SLUG[goal.starterSlug] ?? COURSES[0]!
  const coreCourses = goal.coreSlugs
    .map((slug) => COURSE_BY_SLUG[slug])
    .filter((c): c is CourseSpec => Boolean(c))
  const certification =
    CERTIFICATION_TRACKS.find((t) => t.id === goal.certificationId) ?? CERTIFICATION_TRACKS[0]!
  const firstLabCourse = COURSE_BY_SLUG[goal.firstLabSlug] ?? starter
  return {
    goal,
    starter,
    coreCourses,
    certification,
    firstLabCourse,
    firstLabHref: `/learn/${firstLabCourse.slug}?tab=experiments`,
    docsLinks: goal.docsLinks,
  }
}

export function computeCourseCompletionPct(
  course: CourseSpec,
  progress: CourseProgress | undefined,
): number {
  if (!progress) return 0
  const totalItems = course.lectures.length + course.labSteps.length + 1
  if (totalItems <= 0) return 0
  const doneLectures = course.lectures.filter((l) => progress.completedLectures.includes(l.id)).length
  const doneLabs = course.labSteps.filter((s) => progress.completedLabSteps.includes(s.id)).length
  const doneCapstone = progress.capstone?.submittedAt ? 1 : 0
  return Math.min(100, Math.round(((doneLectures + doneLabs + doneCapstone) / totalItems) * 100))
}

