function buildLectures(seed: CourseSeed): CourseLecture[] {
  return seed.moduleTitles.map((title, idx) => ({
    id: `${seed.slug}-lec-${idx + 1}`,
    number: idx + 1,
    title,
    duration: `${30 + idx * 10} min`,
    summary: `Core theory, Hanzo architecture walkthrough, and worked failure modes for ${title.toLowerCase()}.`,
    topics: [
      `First-principles model of ${title.toLowerCase()}`,
      `Production contract on ${seed.endpoint} with Hanzo IAM org isolation`,
      `Verification invariants, failure recovery, and measurable receipts`,
    ],
    concepts: [seed.concepts[idx]!, `${seed.code} Invariants`, 'Eval-Gated Delivery'],
  }))
}

