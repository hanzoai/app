// What the apps read from @hanzo/personas, from the pinned package.
//
// The team: each member as markdown (team/<id>.md), written to src/team.gen.ts
// as strings, so no host needs an asset loader. Every member the package
// publishes is in it; team.ts draws them in seat order. Beside them, NAMES: the
// name each figure a member is drawn from (its `exemplars`) goes by, read from
// that figure's PERSONA.md. Each member's memoji (assets/memoji/<id>.png) is
// copied to assets/agents/<id>.png, the face a host serves at /agents/<id>.png.
//
// The figures: the roster under personas/, for "Start from a persona". Written
// to assets/personas/ (a build product, ignored by git): index.json lists every
// figure, and <slug>.md is a figure's PERSONA.md where one is written. A host
// serves assets/ at its root, so the list is fetched when it is opened and a
// figure's prompt when it is picked; neither weighs on a bundle.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseFigure } from '@hanzo/personas/figure.js'
import { parse } from '@hanzo/personas/team.js'

const require = createRequire(import.meta.url)
const root = dirname(require.resolve('@hanzo/personas/package.json'))
const here = join(dirname(fileURLToPath(import.meta.url)), '..')
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const ids = readdirSync(join(root, 'team'))
  .filter((f) => f.endsWith('.md'))
  .map((f) => f.slice(0, -3))
  .sort()
const files = Object.fromEntries(ids.map((id) => [id, readFileSync(join(root, 'team', `${id}.md`), 'utf8')]))
const body = ids.map((id) => `  ${id}: ${JSON.stringify(files[id])},`).join('\n')
const drawn = [...new Set(ids.flatMap((id) => parse(id, files[id]).exemplars))].sort()
const names = drawn.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(parseFigure(id, readFileSync(join(root, 'personas', id, 'PERSONA.md'), 'utf8')).name)},`).join('\n')
writeFileSync(
  join(here, 'src', 'team.gen.ts'),
  `// Generated by scripts/team.mjs from @hanzo/personas ${version}. Do not edit.\n` +
    `export const FILES = {\n${body}\n} as const\n\n` +
    `/** The name each figure a member is drawn from goes by, as its PERSONA.md gives it. */\n` +
    `export const NAMES: Readonly<Record<string, string>> = {\n${names}\n}\n`,
)
for (const id of ids) copyFileSync(join(root, 'assets', 'memoji', `${id}.png`), join(here, 'assets', 'agents', `${id}.png`))
console.log(`team: ${ids.length} members from @hanzo/personas ${version}`)

// A PERSONA.md's front matter field, or undefined.
const field = (md, key) => new RegExp(`^${key}:\\s*(.+)$`, 'm').exec(md.split(/^---$/m)[1] ?? '')?.[1].trim()

const out = join(here, 'assets', 'personas')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const portraits = join(root, 'assets', 'personas')
const figures = readdirSync(join(root, 'personas'))
  .sort()
  .map((slug) => {
    const dir = join(root, 'personas', slug)
    const { name, category } = JSON.parse(readFileSync(join(dir, 'profile.json'), 'utf8'))
    const png = join(portraits, `${slug}.png`)
    const svg = join(portraits, `${slug}.svg`)
    let avatar
    if (existsSync(png)) {
      copyFileSync(png, join(out, `${slug}.png`))
      avatar = `/personas/${slug}.png`
    } else if (existsSync(svg)) {
      copyFileSync(svg, join(out, `${slug}.svg`))
      avatar = `/personas/${slug}.svg`
    }
    const at = join(dir, 'PERSONA.md')
    if (!existsSync(at)) return { slug, name, category, ...(avatar ? { avatar } : {}) }
    const md = readFileSync(at, 'utf8')
    writeFileSync(join(out, `${slug}.md`), md)
    const based = field(md, 'based_on')
    return {
      slug,
      name,
      category,
      called: field(md, 'name'),
      about: field(md, 'description'),
      ...(based ? { based } : {}),
      ...(avatar ? { avatar } : {}),
    }
  })
writeFileSync(join(out, 'index.json'), JSON.stringify(figures))
console.log(`figures: ${figures.length}, ${figures.filter((f) => f.called).length} with a PERSONA.md`)
